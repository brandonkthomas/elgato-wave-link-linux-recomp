#!/usr/bin/env python3
"""Generate the QML Icons singleton (glyph names -> Elgato-Icons codepoints) from ElgatoIcons.cs.

usage: gen_icons.py <ElgatoIcons.cs> <out Icons.qml>
"""
import re
import sys
from pathlib import Path

CONST = re.compile(r'public const string (\w+) = "\\u([0-9a-fA-F]{4})"')


def prop_name(name):
    parts = [p for p in name.split("_") if p]
    out = parts[0][0].lower() + parts[0][1:] + "".join(p[0].upper() + p[1:] for p in parts[1:])
    return out if out[0].isalpha() else "i" + out


def main():
    src, out = Path(sys.argv[1]), Path(sys.argv[2])
    seen, lines = set(), []
    for name, code in CONST.findall(src.read_text()):
        prop = prop_name(name)
        if prop in seen:
            continue
        seen.add(prop)
        lines.append(f'    readonly property string {prop}: "\\u{code.lower()}"')
    out.write_text(
        "// Generated by tools/gen_icons.py from Wave Link's ElgatoIcons.cs. Do not edit by hand.\n"
        "// Glyphs render with the Elgato-Icons font (Theme.iconFont).\n"
        "pragma Singleton\nimport QtQuick\n\nQtObject {\n" + "\n".join(lines) + "\n}\n")
    print(f"{len(lines)} glyphs -> {out}")


if __name__ == "__main__":
    main()
