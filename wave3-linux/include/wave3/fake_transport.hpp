// In-memory Wave:3 for tests and UI development: answers GET_MEM/SET_MEM from messages captured on a
// real mic (firmware 1.2.2, API 5.3; its serial replaced with BS0000000000).
#pragma once

#include <map>

#include "wave3/transport.hpp"

namespace wave3 {

class FakeTransport : public Transport {
public:
    FakeTransport() {
        mem_[0] = {0x00, 0x14, 0x00, 0xec, 0x01, 0x01, 0x00, 0x80, 0xea, 0x00, 0x00, 0x00, 0x02, 0x00, 0x00, 0x00};
        mem_[1] = {0x5b, 0x00, 0x00, 0x00, 0x5b, 0x00, 0x00, 0x00};
        mem_[10] = {0x05, 0x03, 0x4b, 0x03, 0x00, 0x0a, 0x00, 0x03, 0x07, 0x03, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
                    0x00, 0x00, 0x00, 0x01, 0x02, 0x02, 0x03, 0x00, 0x00, 0x00, 0x30, 0x62, 0x34, 0x32, 0x35, 0x31, 0x65, 0x65,
                    0x42, 0x53, 0x30, 0x30, 0x30, 0x30, 0x30, 0x30, 0x30, 0x30, 0x30, 0x30, 0x84, 0x03, 0xdc, 0x05};
    }

    std::vector<uint8_t> get_mem(uint8_t id, uint16_t length) override {
        std::vector<uint8_t> m = mem_.at(id);
        m.resize(length);
        return m;
    }

    void set_mem(uint8_t id, const std::vector<uint8_t>& data) override { mem_[id] = data; }

private:
    std::map<uint8_t, std::vector<uint8_t>> mem_;
};

}  // namespace wave3
